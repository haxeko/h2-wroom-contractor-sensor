def patch_stackup(text):
    """Insert the physical stack-up into (setup ...) of the saved board file."""
    lines = ["\t\t(stackup"]
    for name, typ, th, mat, er, lt in STACKUP:
        s = f'\t\t\t(layer "{name}" (type "{typ}")'
        if th is not None:
            s += f" (thickness {th})"
        if mat is not None:
            s += f' (material "{mat}") (epsilon_r {er}) (loss_tangent {lt})'
        lines.append(s + ")")
    lines += ['\t\t\t(copper_finish "ENIG")', "\t\t\t(dielectric_constraints no)", "\t\t)"]
    text = re.sub(r"\n\t\t\(stackup\n.*?\n\t\t\)\n", "\n", text, flags=re.S)
    return text.replace("\t(setup\n", "\t(setup\n" + "\n".join(lines) + "\n", 1)


# ------------------------------------------------------------------------------- board helpers
def load_fp(lib_id):
    nick, name = lib_id.split(":", 1)
    path = FP_DIRS.get(nick, KICAD_FP / f"{nick}.pretty")
    fp = pcbnew.FootprintLoad(str(path), name)
    if fp is None:
        raise SystemExit(f"footprint {lib_id} not found in {path}")
    return fp


def add_outline(board):
    r = CORNER_R
    pts = [((r, 0), (BW - r, 0)), ((BW, r), (BW, BH - r)), ((BW - r, BH), (r, BH)), ((0, BH - r), (0, r))]
    for a, b in pts:
        s = pcbnew.PCB_SHAPE(board)
        s.SetShape(pcbnew.SHAPE_T_SEGMENT)
        s.SetStart(P(*a))
        s.SetEnd(P(*b))
        s.SetLayer(pcbnew.Edge_Cuts)
        s.SetWidth(mm(0.05))
        board.Add(s)
    k = r * (1 - math.sqrt(0.5))
    for st, mid, en in (((0, r), (k, k), (r, 0)), ((BW - r, 0), (BW - k, k), (BW, r)),
                        ((BW, BH - r), (BW - k, BH - k), (BW - r, BH)), ((r, BH), (k, BH - k), (0, BH - r))):
        a = pcbnew.PCB_SHAPE(board)
        a.SetShape(pcbnew.SHAPE_T_ARC)
        a.SetArcGeometry(P(*st), P(*mid), P(*en))
        a.SetLayer(pcbnew.Edge_Cuts)
        a.SetWidth(mm(0.05))
        board.Add(a)


def make_zone(board, layer, net, pts, priority=0, rule_area=None, name=""):
    z = pcbnew.ZONE(board)
    z.SetLayer(layer)
    if rule_area:
        z.SetIsRuleArea(True)
        z.SetLayerSet(rule_area["layers"])
        z.SetDoNotAllowTracks(rule_area.get("tracks", True))
        z.SetDoNotAllowVias(rule_area.get("vias", True))
        z.SetDoNotAllowZoneFills(rule_area.get("fills", True))
        z.SetDoNotAllowPads(False)
        z.SetDoNotAllowFootprints(False)
    else:
        z.SetNet(net)
        z.SetAssignedPriority(priority)
        z.SetLocalClearance(mm(0.2))
        z.SetMinThickness(mm(0.15))
        z.SetThermalReliefGap(mm(0.2))
        z.SetThermalReliefSpokeWidth(mm(0.25))
        z.SetPadConnection(pcbnew.ZONE_CONNECTION_THERMAL)
        z.SetIslandRemovalMode(pcbnew.ISLAND_REMOVAL_MODE_ALWAYS)
    if name:
        z.SetZoneName(name)
    ol = z.Outline()
    ol.NewOutline()
    for x, y in pts:
        ol.Append(mm(OX + x), mm(OY + y))
    board.Add(z)
    return z


def rect_pts(x0, y0, x1, y1):
    return [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]


# ------------------------------------------------------------------------------- build
def build(args):
    comps, nets = export_netlist()
    write_project_settings()
    if PCB.exists():
        PCB.unlink()
    board = pcbnew.NewBoard(str(PCB))
    board.SetCopperLayerCount(COPPER_LAYERS)
    ds = board.GetDesignSettings()
    ds.SetBoardThickness(mm(1.0))
    ds.SetAuxOrigin(P(0, BH))           # drill / place origin = lower-left board corner (fab files)

    # nets
    netinfo = {}
    for name in sorted(nets):
        ni = pcbnew.NETINFO_ITEM(board, name)
        board.Add(ni)
        netinfo[name] = ni

    pad_net = {}
    for name, nodes in nets.items():
        for ref, pin in nodes:
            pad_net[(ref, pin)] = name

    dnp = {p.ref: p.dnp for p in PARTS}
    fps = {}
    for ref, c in sorted(comps.items()):
        fp = load_fp(c["footprint"])
        fp.SetReference(ref)
        fp.SetValue(c["value"])
        fp.SetFPIDAsString(c["footprint"])
        fp.SetPath(pcbnew.KIID_PATH("/" + c["tstamp"]))
        fp.SetSheetname("/")
        fp.SetSheetfile(f"{PROJECT}.kicad_sch")
        for k, v in c["fields"].items():
            if k in ("Footprint", "Datasheet", "Description", "Reference", "Value"):
                continue
            fp.SetField(k, v)
            fld = fp.GetField(k)
            if fld:
                fld.SetVisible(False)
                fld.SetLayer(pcbnew.F_Fab)
        fp.SetDNP(bool(dnp.get(ref)))
        for fname in ("Datasheet", "Description"):
            fld = fp.GetField(fname)
            if fld is not None:
                fld.SetText(c[fname.lower()])
        if ref == "J2":
            fp.SetAllowSolderMaskBridges(True)   # Hirose footprint: one mask window over the connector
        if ref in ("U1", "U2"):
            ep = {"U1": "33", "U2": "11"}[ref]
            for pad in fp.Pads():
                if pad.GetNumber() == ep:
                    pad.SetLocalZoneConnection(pcbnew.ZONE_CONNECTION_FULL)
        board.Add(fp)
        if ref not in PLACEMENT:
            raise SystemExit(f"no placement for {ref}")
        pl = PLACEMENT[ref]
        x, y, rot = pl[:3]
        fp.SetPosition(P(x, y))
        fp.SetOrientationDegrees(rot)
        if len(pl) > 3 and pl[3] == "B":
            fp.Flip(fp.GetPosition(), pcbnew.FLIP_DIRECTION_LEFT_RIGHT)
        # silkscreen reference: small, hidden on dense parts (assembly drawing uses F.Fab)
        fp.Reference().SetVisible(False)
        for pad in fp.Pads():
            key = (ref, pad.GetNumber())
            if key in pad_net:
                pad.SetNet(netinfo[pad_net[key]])
        fps[ref] = fp

    count = {}
    for lib, name, x, y, side in BOARD_ONLY:
        fp = load_fp(f"{lib}:{name}")
        prefix = "FID" if lib == "Fiducial" else "H"
        count[prefix] = count.get(prefix, 0) + 1
        fp.SetReference(f"{prefix}{count[prefix]}")          # unique: FID1/FID2 in the pick & place file
        fp.SetBoardOnly(True)
        fp.SetExcludedFromBOM(True)
        board.Add(fp)
        fp.SetPosition(P(x, y))
        fp.Reference().SetVisible(False)

    add_outline(board)
    return board, fps, netinfo, nets


def crtyd_box(fp):
    cy = fp.GetCourtyard(pcbnew.B_CrtYd if fp.IsFlipped() else pcbnew.F_CrtYd)
    if cy.OutlineCount() == 0:
        bb = fp.GetBoundingBox(False)
    else:
        bb = cy.BBox()
    return (pcbnew.ToMM(bb.GetLeft()) - OX, pcbnew.ToMM(bb.GetTop()) - OY,
            pcbnew.ToMM(bb.GetRight()) - OX, pcbnew.ToMM(bb.GetBottom()) - OY)


def legalise(fps):
    """Move non-FIXED parts (in PLACEMENT order) to the nearest position where their courtyard does
    not overlap an already placed courtyard on the same side. Deterministic spiral search."""
    placed = []
    order = [r for r in PLACEMENT if r in FIXED] + [r for r in PLACEMENT if r not in FIXED]
    moved = []
    g = COURTYARD_GAP
    for ref in order:
        fp = fps[ref]
        side = fp.IsFlipped()
        x0, y0, x1, y1 = crtyd_box(fp)
        px, py = to_rel(fp.GetPosition())

        def ok(dx, dy):
            a = (x0 + dx, y0 + dy, x1 + dx, y1 + dy)
            if ref not in FIXED and (a[0] < 0 or a[1] < 0 or a[2] > BW or a[3] > BH):
                return False
            for s2, b in placed:
                if s2 == side and a[0] < b[2] + g and b[0] < a[2] + g and a[1] < b[3] + g and b[1] < a[3] + g:
                    return False
            return True

        best = (0.0, 0.0)
        if ref not in FIXED and not ok(0, 0):
            best = None
            step = 0.05
            for ring in range(1, 120):
                r = ring * step
                cands = []
                n = max(8, int(2 * math.pi * r / step))
                for k in range(n):
                    a = 2 * math.pi * k / n
                    cands.append((round(r * math.cos(a) / 0.05) * 0.05, round(r * math.sin(a) / 0.05) * 0.05))
                cands.sort(key=lambda d: (abs(d[0]) + abs(d[1]), d))
                for dx, dy in cands:
                    if ok(dx, dy):
                        best = (dx, dy)
                        break
                if best:
                    break
            if best is None:
                print(f"legaliser: NO ROOM for {ref}, left at its preferred position")
                best = (0.0, 0.0)
            fp.SetPosition(P(px + best[0], py + best[1]))
            moved.append((ref, round(best[0], 2), round(best[1], 2)))
        placed.append((side, (x0 + best[0], y0 + best[1], x1 + best[0], y1 + best[1])))
    return moved



