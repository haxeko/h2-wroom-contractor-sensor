def point_in_poly(x, y, pts):
    inside = False
    n = len(pts)
    for a in range(n):
        xa, ya = pts[a]
        xb, yb = pts[(a + 1) % n]
        if (ya > y) != (yb > y) and x < xa + (y - ya) * (xb - xa) / (yb - ya):
            inside = not inside
    return inside


def inset_ok(x, y, pts, d):
    """Point inside polygon and at least d from its border (checked on 8 directions)."""
    if not point_in_poly(x, y, pts):
        return False
    for k in range(8):
        a = k * math.pi / 4
        if not point_in_poly(x + d * math.cos(a), y + d * math.sin(a), pts):
            return False
    return True


class Router:
    def __init__(self, board, fps, netinfo):
        self.board, self.fps, self.netinfo = board, fps, netinfo
        self.nid = {name: i + 1 for i, name in enumerate(sorted(netinfo))}
        self.name_of = {v: k for k, v in self.nid.items()}
        self.g = Grid(0.0, 0.0, BW, BH, GRID_PITCH, ROUTE_LAYERS, BASE_W / 2)
        self.vias = []                       # (x, y) of every hole: vias + footprint thermal vias
        self.tree = {}                       # net -> set of (L, i, j): copper of the net (island membership)
        self.anchor = {}                     # net -> nodes lying exactly on copper (valid route end points)
        self.tracks = {}                     # net -> list of PCB_TRACK
        self.stats = {"tracks": 0, "vias": 0}
        self.via_layers = list(range(len(ROUTE_LAYERS)))
        self.failed = []

    # ---------------------------------------------------------------- obstacles
    def pad_rect(self, pad):
        bb = pad.GetBoundingBox()
        x0, y0 = pcbnew.ToMM(bb.GetLeft()) - OX, pcbnew.ToMM(bb.GetTop()) - OY
        x1, y1 = pcbnew.ToMM(bb.GetRight()) - OX, pcbnew.ToMM(bb.GetBottom()) - OY
        return (x0 + x1) / 2, (y0 + y1) / 2, (x1 - x0) / 2, (y1 - y0) / 2

    def pad_layers(self, pad):
        out = []
        for i, name in enumerate(ROUTE_LAYERS):
            if pad.IsOnLayer(LAYER_ID[name]):
                out.append(i)
        return out

    def add_obstacles(self):
        for fp in self.board.GetFootprints():
            # keep-out rule areas defined inside footprints (e.g. Hirose MS-156C3)
            for z in fp.Zones():
                if not z.GetIsRuleArea() or not (z.GetDoNotAllowTracks() or z.GetDoNotAllowVias()):
                    continue
                ol = z.Outline()
                pts = []
                for k in range(ol.OutlineCount()):
                    o = ol.Outline(k)
                    for q in range(o.PointCount()):
                        pt = o.CPoint(q)
                        pts.append((pcbnew.ToMM(pt.x) - OX, pcbnew.ToMM(pt.y) - OY))
                lys = [L for L in ROUTE_LAYERS if z.IsOnLayer(LAYER_ID[L])]
                if pts and lys:
                    self.g.add_rule_poly(lys, pts, Rule(f"keepout {fp.GetReference()}"))
            pad_clr = 0.5 if fp.IsBoardOnly() else None
            for pad in fp.Pads():
                attr = pad.GetAttribute()
                cx, cy, hw, hh = self.pad_rect(pad)
                if attr == pcbnew.PAD_ATTRIB_NPTH:
                    for L in range(len(ROUTE_LAYERS)):
                        self.g.add_circle(ROUTE_LAYERS[L], cx, cy, max(hw, hh), -1, 0.25)
                    self.vias.append((cx, cy))
                    self.g.add_hole(cx, cy, max(hw, hh) + 0.25 + 0.15)
                    continue
                net = pad.GetNetname()
                nid = self.nid.get(net, -1) if net else -1
                if not pad.IsOnCopperLayer():
                    continue                   # paste-only apertures
                clr = 0.2 if net in RF_NETS else CLR
                if pad_clr:
                    clr = pad_clr
                for L in self.pad_layers(pad):
                    if pad.GetShape() == pcbnew.PAD_SHAPE_CIRCLE:
                        self.g.add_circle(ROUTE_LAYERS[L], cx, cy, hw, nid, clr)
                        self.g.add_rect(ROUTE_LAYERS[L], cx, cy, hw * 0.7, hh * 0.7, nid, 0.0, pad=True)
                    else:
                        self.g.add_rect(ROUTE_LAYERS[L], cx, cy, hw, hh, nid, clr, pad=True)
                if attr == pcbnew.PAD_ATTRIB_PTH:
                    self.vias.append((cx, cy))
                    drill = pcbnew.ToMM(max(pad.GetDrillSize().x, pad.GetDrillSize().y)) / 2
                    self.g.add_hole(cx, cy, drill + 0.25 + 0.15)
        # board edge and antenna keep-out (track centre lines)
        e = 0.3 + BASE_W / 2 + 0.03
        edge = Rule("edge")
        for L in ROUTE_LAYERS:
            self.g.add_rule_rect([L], 0, 0, BW, e, edge)
            self.g.add_rule_rect([L], 0, BH - e, BW, BH, edge)
            self.g.add_rule_rect([L], 0, 0, e, BH, edge)
            self.g.add_rule_rect([L], BW - e, 0, BW, BH, edge)
        self.g.add_rule_rect(ROUTE_LAYERS, 0, 0, ANT_KEEPOUT_X + BASE_W / 2 + 0.03, BH, Rule("antenna"))
        gnd = self.nid["/GND"]
        # RF chain: nothing but GND stitching, every layer
        self.g.add_rule_poly(ROUTE_LAYERS, RF_POLY, Rule("rf", [gnd]))
        # 32 MHz crystal: clock nets only on L1, nothing on the other layers
        y1 = crtyd_box(self.fps["Y1"])
        xt = [self.nid["/XTAL_N"], self.nid["/XTAL_P_X"], gnd]
        self.g.add_rule_rect(["F.Cu"], y1[0], y1[1], y1[2], y1[3], Rule("xtal-top", xt))
        self.g.add_rule_rect(["In2.Cu", "B.Cu"], y1[0] - 0.3, y1[1] - 0.3, y1[2] + 0.3, y1[3] + 0.3,
                             Rule("xtal-inner", [gnd]))

    # ---------------------------------------------------------------- commit helpers
    def ij2xy(self, i, j):
        return self.g.xy(i, j)

    def add_track(self, net, layer, a, b, width):
        t = pcbnew.PCB_TRACK(self.board)
        t.SetStart(P(*a))
        t.SetEnd(P(*b))
        t.SetWidth(mm(width))
        t.SetLayer(LAYER_ID[layer])
        t.SetNet(self.netinfo[net])
        self.board.Add(t)
        self.tracks.setdefault(net, []).append(t)
        clr = 0.31 if net in RF_NETS else CLR
        if layer in ROUTE_LAYERS:
            self.g.add_segment(layer, a[0], a[1], b[0], b[1], width / 2, self.nid[net], clr)
            L = ROUTE_LAYERS.index(layer)
            n = max(1, int(math.hypot(b[0] - a[0], b[1] - a[1]) / GRID_PITCH) * 2)
            tr = self.tree.setdefault(net, set())
            an = self.anchor.setdefault(net, set())
            vx, vy = b[0] - a[0], b[1] - a[1]
            ll = vx * vx + vy * vy
            for k in range(n + 1):
                i, j = self.g.ij(a[0] + vx * k / n, a[1] + vy * k / n)
                tr.add((L, i, j))
                x, y = self.g.xy(i, j)
                tp = 0.0 if ll == 0 else max(0.0, min(1.0, ((x - a[0]) * vx + (y - a[1]) * vy) / ll))
                if (a[0] + tp * vx - x) ** 2 + (a[1] + tp * vy - y) ** 2 < 1e-8:
                    an.add((L, i, j))
        self.stats["tracks"] += 1
        return t

    def add_via(self, net, x, y, size=None):
        size = size or VIA
        v = pcbnew.PCB_VIA(self.board)
        v.SetPosition(P(x, y))
        v.SetWidth(mm(size[0]))
        v.SetDrill(mm(size[1]))
        v.SetViaType(pcbnew.VIATYPE_THROUGH)
        v.SetLayerPair(pcbnew.F_Cu, pcbnew.B_Cu)
        v.SetNet(self.netinfo[net])
        self.board.Add(v)
        for L in ROUTE_LAYERS:
            self.g.add_circle(L, x, y, size[0] / 2, self.nid[net], CLR)
        i, j = self.g.ij(x, y)
        if abs(self.g.xy(i, j)[0] - x) < 1e-4 and abs(self.g.xy(i, j)[1] - y) < 1e-4:
            for L in range(len(ROUTE_LAYERS)):
                self.tree.setdefault(net, set()).add((L, i, j))
                self.anchor.setdefault(net, set()).add((L, i, j))
        self.vias.append((x, y))
        self.g.add_hole(x, y, size[1] / 2 + 0.25 + 0.15)
        self.stats["vias"] += 1
        return v

    def via_spacing_ok(self, x, y):
        for vx, vy in self.vias:
            if (vx - x) ** 2 + (vy - y) ** 2 < VIA_MIN_PITCH ** 2:
                return False
        return True

    def split_at(self, net, layer, x, y):
        """Split a track of `net` whose interior contains (x, y) so a T-junction has real end points."""
        lid = LAYER_ID[layer]
        for t in list(self.tracks.get(net, [])):
            if t.GetLayer() != lid:
                continue
            ax, ay = to_rel(t.GetStart())
            bx, by = to_rel(t.GetEnd())
            if (abs(ax - x) < 1e-3 and abs(ay - y) < 1e-3) or (abs(bx - x) < 1e-3 and abs(by - y) < 1e-3):
                return
            vx, vy = bx - ax, by - ay
            ll = vx * vx + vy * vy
            if ll == 0:
                continue
            tpar = ((x - ax) * vx + (y - ay) * vy) / ll
            if 0 < tpar < 1:
                px, py = ax + tpar * vx, ay + tpar * vy
                if (px - x) ** 2 + (py - y) ** 2 < 1e-6:
                    t.SetEnd(P(x, y))
                    t2 = pcbnew.PCB_TRACK(self.board)
                    t2.SetStart(P(x, y))
                    t2.SetEnd(P(bx, by))
                    t2.SetWidth(t.GetWidth())
                    t2.SetLayer(lid)
                    t2.SetNet(self.netinfo[net])
                    self.board.Add(t2)
                    self.tracks[net].append(t2)
                    return

    def commit_path(self, net, path, width, end_via=False, via_size=None, start_xy=None):
        via_size = via_size or VIA
        segs, vias = path_to_segments(path)
        if start_xy is not None and len(path) >= 1:
            # plane connection: pad centre -> via, as one straight segment when the path is straight
            x, y = self.ij2xy(path[-1][1], path[-1][2])
            if not segs or len(segs) == 1:
                self.add_track(net, ROUTE_LAYERS[path[0][0]], start_xy, (x, y), width)
                segs = []
        for L, a, b in segs:
            self.add_track(net, ROUTE_LAYERS[L], self.ij2xy(*a), self.ij2xy(*b), width)
        for (i, j) in vias:
            x, y = self.ij2xy(i, j)
            self.add_via(net, x, y, via_size)
        if end_via:
            x, y = self.ij2xy(path[-1][1], path[-1][2])
            self.add_via(net, x, y, via_size)
        tr = self.tree.setdefault(net, set())
        an = self.anchor.setdefault(net, set())
        for node in path:
            tr.add(node)
            an.add(node)
        for (i, j) in vias:
            for L in range(len(ROUTE_LAYERS)):
                tr.add((L, i, j))
                an.add((L, i, j))
        if end_via:
            i, j = path[-1][1], path[-1][2]
            for L in range(len(ROUTE_LAYERS)):
                tr.add((L, i, j))
                an.add((L, i, j))
        # T-junctions at both ends of the path
        for L, i, j in (path[-1], path[0]):
            x, y = self.ij2xy(i, j)
            self.split_at(net, ROUTE_LAYERS[L], x, y)

    # ---------------------------------------------------------------- pads -> nodes
    def pad_nodes(self, pad, net, raw=False):
        nid = self.nid[net]
        cx, cy, hw, hh = self.pad_rect(pad)
        if pad.GetShape() == pcbnew.PAD_SHAPE_CIRCLE:
            hw = hh = hw * 0.7
        i0, j0 = self.g.ij(cx - hw, cy - hh)
        i1, j1 = self.g.ij(cx + hw, cy + hh)
        out = []
        for L in self.pad_layers(pad):
            for j in range(j0, j1 + 1):
                for i in range(i0, i1 + 1):
                    x, y = self.g.xy(i, j)
                    if abs(x - cx) <= hw - 0.02 and abs(y - cy) <= hh - 0.02 and \
                            (raw or self.g.passable(L, j * self.g.nx + i, nid)) and pad.HitTest(P(x, y)):
                        out.append((L, i, j))
        return out

    def net_pads(self, net):
        out = []
        for fp in self.board.GetFootprints():
            for pad in fp.Pads():
                if pad.GetNetname() == net and pad.GetNumber():
                    out.append((fp.GetReference(), pad))
        return out

    # ---------------------------------------------------------------- fixed RF route
    def pad_xy(self, ref, num):
        for pad in self.fps[ref].Pads():
            if pad.GetNumber() == num:
                return to_rel(pad.GetPosition())
        raise KeyError((ref, num))

    def route_rf(self):
        w = 0.32
        pa = self.pad_xy
        chain = [("/RF_ANT", ("ANT1", "1"), ("L6", "2")), ("/RF_50R", ("L6", "1"), ("J2", "A")),
                 ("/RF_M1", ("J2", "C"), ("C21", "2")), ("/RF_A", ("C21", "1"), ("L4", "2")),
                 ("/LNA_IN", ("L4", "1"), ("C19", "1"))]
        for net, a, b in chain:
            self.add_track(net, "F.Cu", pa(*a), pa(*b), w)
        stubs = [("/RF_ANT", ("L6", "2"), ("C23", "1")), ("/RF_50R", ("L6", "1"), ("C22", "1")),
                 ("/RF_M1", ("C21", "2"), ("L5", "1")), ("/RF_A", ("L4", "2"), ("C20", "1"))]
        for net, a, b in stubs:
            self.add_track(net, "F.Cu", pa(*a), pa(*b), w)
        # C19 -> ANT pin: 45 deg away from the VDD3P3 pins, last 0.4 mm narrowed to the pad width
        x0, y0 = pa("C19", "1")
        px, py = pa("U1", "32")
        tip = px - 0.388
        dy = y0 - py
        a1 = (x0 + 0.2, y0)
        a2 = (tip - 0.4 + 0.2, py + 0.2)
        a3 = (tip - 0.2, py)
        self.add_track("/LNA_IN", "F.Cu", (x0, y0), a1, w)
        self.add_track("/LNA_IN", "F.Cu", a1, a2, w)
        self.add_track("/LNA_IN", "F.Cu", a2, a3, 0.2)
        self.add_track("/LNA_IN", "F.Cu", a3, (px, py), 0.2)
        # Espressif 2nd-harmonic stub on the GND pad of the first shunt capacitor (C19):
        # 15 mil long, ~100 Ohm (0.29 mm on L1 referenced to L3, L2 removed underneath) -> GND via
        gx, gy = pa("C19", "2")
        vy = round(gy + 0.23 + STUB_LEN + VIA[0] / 2, 3)
        self.add_track("/GND", "F.Cu", (gx, gy), (gx, vy), STUB_W)
        self.add_via("/GND", gx, vy)
        return (gx, gy)

