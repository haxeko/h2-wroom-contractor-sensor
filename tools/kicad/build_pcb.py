def mm(v):
    return pcbnew.FromMM(v)


def P(x, y):
    return pcbnew.VECTOR2I(mm(OX + x), mm(OY + y))


def to_rel(v):
    return pcbnew.ToMM(v.x) - OX, pcbnew.ToMM(v.y) - OY


# ------------------------------------------------------------------------------- netlist
def export_netlist():
    with tempfile.TemporaryDirectory() as td:
        out = pathlib.Path(td) / "net.net"
        subprocess.run(["kicad-cli", "sch", "export", "netlist", "--format", "kicadsexpr", "-o", str(out), str(SCH)],
                       check=True, capture_output=True)
        tree = loads(out.read_text())
    comps = {}
    for c in find_all(find(tree, Sym("components")), Sym("comp")):
        ref = find(c, Sym("ref"))[1]
        comps[ref] = {
            "value": find(c, Sym("value"))[1],
            "footprint": find(c, Sym("footprint"))[1],
            "tstamp": find(c, Sym("tstamps"))[1],
            "fields": {find(f, Sym("name"))[1]: (f[2] if len(f) > 2 else "")
                       for f in find_all(find(c, Sym("fields")), Sym("field"))},
            "datasheet": (find(c, Sym("datasheet")) or [None, ""])[1],
            "description": (find(c, Sym("description")) or [None, ""])[1],
        }
    nets = {}
    for n in find_all(find(tree, Sym("nets")), Sym("net")):
        name = find(n, Sym("name"))[1]
        nets[name] = [(find(nd, Sym("ref"))[1], find(nd, Sym("pin"))[1]) for nd in find_all(n, Sym("node"))]
    return comps, nets


